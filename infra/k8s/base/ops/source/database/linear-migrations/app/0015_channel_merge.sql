-- Channel merge bookkeeping for Podcast Index feeds marked as duplicates of a surviving feed.
-- A merged feed stays in the database and is not parsed or public.

INSERT INTO public.feed_lifecycle_state_type (id, state_key, created_at, updated_at)
VALUES (5, 'merged', '2000-01-01 00:00:00', '2000-01-01 00:00:00');

SELECT setval('public.feed_lifecycle_state_type_id_seq', 5, true);

CREATE TABLE public.channel_merge (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_podcast_index_id integer NOT NULL,
    to_podcast_index_id integer NOT NULL,
    from_channel_id integer,
    to_channel_id integer,
    mode text,
    status text NOT NULL,
    confidence numeric(5, 4),
    match_stats jsonb DEFAULT '{}'::jsonb NOT NULL,
    note text,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    applied_at timestamp with time zone
);

ALTER TABLE ONLY public.channel_merge
    ADD CONSTRAINT channel_merge_from_podcast_index_id_key UNIQUE (from_podcast_index_id);

ALTER TABLE ONLY public.channel_merge
    ADD CONSTRAINT channel_merge_mode_check
    CHECK (mode IS NULL OR mode IN ('repoint', 'absorb'));

ALTER TABLE ONLY public.channel_merge
    ADD CONSTRAINT channel_merge_status_check
    CHECK (status IN ('detected', 'verified', 'needs_review', 'applied', 'rejected', 'reverted'));

ALTER TABLE ONLY public.channel_merge
    ADD CONSTRAINT channel_merge_confidence_check
    CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1));

ALTER TABLE ONLY public.channel_merge
    ADD CONSTRAINT channel_merge_from_channel_id_fkey
    FOREIGN KEY (from_channel_id) REFERENCES public.channel(id);

ALTER TABLE ONLY public.channel_merge
    ADD CONSTRAINT channel_merge_to_channel_id_fkey
    FOREIGN KEY (to_channel_id) REFERENCES public.channel(id);

CREATE INDEX idx_channel_merge_status ON public.channel_merge (status);

CREATE INDEX idx_channel_merge_to_podcast_index_id ON public.channel_merge (to_podcast_index_id);

CREATE TRIGGER set_updated_at_channel_merge
    BEFORE UPDATE ON public.channel_merge
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at_field();

CREATE TABLE public.item_merge_map (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_merge_id integer NOT NULL,
    from_item_id integer NOT NULL,
    to_item_id integer,
    match_tier text
);

ALTER TABLE ONLY public.item_merge_map
    ADD CONSTRAINT item_merge_map_channel_merge_from_item_key
    UNIQUE (channel_merge_id, from_item_id);

ALTER TABLE ONLY public.item_merge_map
    ADD CONSTRAINT item_merge_map_match_tier_check
    CHECK (match_tier IS NULL OR match_tier IN ('guid', 'enclosure', 'fuzzy'));

ALTER TABLE ONLY public.item_merge_map
    ADD CONSTRAINT item_merge_map_channel_merge_id_fkey
    FOREIGN KEY (channel_merge_id) REFERENCES public.channel_merge(id) ON DELETE CASCADE;

ALTER TABLE ONLY public.item_merge_map
    ADD CONSTRAINT item_merge_map_from_item_id_fkey
    FOREIGN KEY (from_item_id) REFERENCES public.item(id);

ALTER TABLE ONLY public.item_merge_map
    ADD CONSTRAINT item_merge_map_to_item_id_fkey
    FOREIGN KEY (to_item_id) REFERENCES public.item(id);

CREATE TABLE public.channel_merge_journal (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_merge_id integer NOT NULL,
    table_name text NOT NULL,
    row_pk text NOT NULL,
    action text NOT NULL,
    before_json jsonb,
    after_json jsonb,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

ALTER TABLE ONLY public.channel_merge_journal
    ADD CONSTRAINT channel_merge_journal_action_check
    CHECK (action IN ('insert', 'update', 'delete'));

ALTER TABLE ONLY public.channel_merge_journal
    ADD CONSTRAINT channel_merge_journal_channel_merge_id_fkey
    FOREIGN KEY (channel_merge_id) REFERENCES public.channel_merge(id) ON DELETE CASCADE;

CREATE TABLE public.podcast_index_dead_feed_sync (
    id smallint PRIMARY KEY,
    last_modified text,
    etag text,
    synced_at timestamp with time zone,
    CONSTRAINT podcast_index_dead_feed_sync_singleton CHECK (id = 1)
);

