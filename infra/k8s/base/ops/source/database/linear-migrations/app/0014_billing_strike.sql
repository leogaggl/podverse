-- Checkout sessions map a processor checkout attempt to an account and catalog product before a
-- payment exists, so webhook and reconcile flows can resolve ownership when the payment settles.

CREATE TABLE public.billing_checkout_session (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    processor_id character varying(32) NOT NULL,
    external_id text NOT NULL,
    account_id integer NOT NULL,
    billing_processor_product_id integer NOT NULL,
    amount numeric(19,4) NOT NULL,
    currency_code character(3) NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    settled_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT billing_checkout_session_amount_check CHECK ((amount >= (0)::numeric))
);

ALTER TABLE ONLY public.billing_checkout_session
    ADD CONSTRAINT billing_checkout_session_processor_external_key
    UNIQUE (processor_id, external_id);

ALTER TABLE ONLY public.billing_checkout_session
    ADD CONSTRAINT billing_checkout_session_account_id_fkey
    FOREIGN KEY (account_id) REFERENCES public.account(id) ON DELETE CASCADE;

ALTER TABLE ONLY public.billing_checkout_session
    ADD CONSTRAINT billing_checkout_session_processor_id_fkey
    FOREIGN KEY (processor_id) REFERENCES public.billing_processor(id);

ALTER TABLE ONLY public.billing_checkout_session
    ADD CONSTRAINT billing_checkout_session_billing_processor_product_id_fkey
    FOREIGN KEY (billing_processor_product_id) REFERENCES public.billing_processor_product(id);

CREATE INDEX idx_billing_checkout_session_account_id
    ON public.billing_checkout_session USING btree (account_id);

CREATE INDEX idx_billing_checkout_session_unsettled_processor_created_at
    ON public.billing_checkout_session USING btree (processor_id, created_at)
    WHERE (settled_at IS NULL);

